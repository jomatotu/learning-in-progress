import json

from fastapi.testclient import TestClient

from app import hermes
from app.main import app

client = TestClient(app)

REQUEST = {"profile": {"material": {"topic": "Zellen", "text": "DNA ist der Träger der Erbinformation."}}}

SPEC = {
    "root": "lesson",
    "elements": {
        "lesson": {"type": "Lesson", "props": {"title": "Zellen"}, "children": ["c1", "q1"]},
        "c1": {
            "type": "Chunk",
            "props": {"heading": "DNA", "text": "DNA speichert Gene.", "source": "DNA ist der Träger der Erbinformation."},
            "children": [],
        },
        "q1": {
            "type": "Quiz",
            "props": {
                "question": "Was speichert die DNA?",
                "options": ["Gene", "Fett"],
                "answer": 0,
                "explanation": "DNA trägt die Erbinformation.",
                "source": "DNA ist der Träger der Erbinformation.",
            },
            "children": [],
        },
    },
}


# Fakes the Hermes stream underneath stream_hermes_json: each call replies with the next text.
def fake_hermes(monkeypatch, *replies: str) -> list[dict]:
    calls = []

    async def stream_hermes(message, session_id=None, instructions=None):
        calls.append({"message": message, "session_id": session_id, "instructions": instructions})
        yield "text", replies[len(calls) - 1]

    monkeypatch.setattr(hermes, "stream_hermes", stream_hermes)
    return calls


def test_valid_spec_is_returned_with_profile_fenced_as_data(monkeypatch):
    calls = fake_hermes(monkeypatch, json.dumps(SPEC))

    response = client.post("/api/solution", json=REQUEST)

    assert response.status_code == 200
    assert response.json() == {"spec": SPEC}
    assert len(calls) == 1
    assert "<student_profile>" in calls[0]["message"]
    assert "DNA ist der Träger der Erbinformation." in calls[0]["message"]
    # The catalog Hermes builds from, generated by the client.
    assert '"Quiz"' in calls[0]["instructions"]
    assert calls[0]["session_id"].startswith("lip-solution-")


def test_invalid_spec_is_retried_once(monkeypatch):
    calls = fake_hermes(monkeypatch, "Hier ist deine Seite!", json.dumps(SPEC))

    response = client.post("/api/solution", json=REQUEST)

    assert response.status_code == 200
    assert response.json() == {"spec": SPEC}
    assert len(calls) == 2
    assert calls[1]["session_id"] == calls[0]["session_id"]


def test_spec_that_breaks_the_catalog_twice_gives_a_german_error(monkeypatch):
    unknown = {**SPEC, "elements": {**SPEC["elements"], "c1": {"type": "Video", "props": {}, "children": []}}}
    missing_child = {**SPEC, "elements": {"lesson": SPEC["elements"]["lesson"]}}
    calls = fake_hermes(monkeypatch, json.dumps(unknown), json.dumps(missing_child))

    response = client.post("/api/solution", json=REQUEST)

    assert response.status_code == 502
    assert response.json()["detail"] == "Deine Seite konnte nicht gebaut werden. Versuch es nochmal."
    assert len(calls) == 2
    assert "Video" in calls[1]["message"]


def test_quiz_without_source_is_rejected(monkeypatch):
    no_source = json.loads(json.dumps(SPEC))
    del no_source["elements"]["q1"]["props"]["source"]
    calls = fake_hermes(monkeypatch, json.dumps(no_source), json.dumps(no_source))

    response = client.post("/api/solution", json=REQUEST)

    assert response.status_code == 502
    assert "source" in calls[1]["message"]
